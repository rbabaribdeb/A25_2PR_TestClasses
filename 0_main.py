# 1- Objet de type str
print("message")
print(type("message")) # <class 'str'>

# 2- Objet de type int
print(type(6))

# 3- Objet de type liste
liste = []
print(type(liste))


# Une classe vs Objet:
# Une classe est un regroupement de attributs (DATA) et de méthodes (FAIRE)
# La classe decrit le comportement de l'objet dans un fichier
# La classe === un fichier dans le disque
# L'objet === la representation dans la mémoire

